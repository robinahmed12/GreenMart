export function product(
  slug: string,
  name: string,
  categorySlug: string,
  priceAmount: number,
  sellingUnit: SellingUnit,
  stockStatus: StockStatus,
  description: string,
  extras: Partial<Pick<SeedProduct, "aliases" | "imageUrl" | "images" | "origin" | "storage" | "preparation" | "nutrition" | "allergens">> = {},
): SeedProduct {
  return {
    slug,
    name,
    categorySlug,
    price: price(priceAmount),
    sellingUnit,
    stockStatus,
    description,
    aliases: [],
    ...extras,
  };
}

